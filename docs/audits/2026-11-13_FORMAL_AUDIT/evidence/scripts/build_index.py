import re,os,sys,csv,collections,json
A=sys.argv[1]; P=os.path.join(A,'plan')
def cards(path,prefix):
    txt=open(path,encoding='utf-8').read()
    parts=re.split(r'(?m)^### ('+prefix+r'-[A-Z0-9]+-\d+[a-z]?) ',txt)
    out=[]
    for i in range(1,len(parts),2):
        cid=parts[i]; body=parts[i+1]; title=body.split('\n',1)[0].strip()
        f={}
        for m in re.finditer(r'(?m)^\|\s*([A-Za-z /]+?)\s*\|\s*(.*?)\s*\|\s*$',body[:3000]):
            f[m.group(1).strip().lower()]=m.group(2).strip()
        issues=sorted({int(x) for x in re.findall(r'#(\d{2,4})\b', f.get('issues',''))})
        out.append(dict(id=cid,title=title,fields=f,issues=issues,body=body))
    return out
def short(s,n):
    s=re.sub(r'\s+',' ',s or ''); return s if len(s)<=n else s[:n-1]+'…'
order=['H','G','P','T','CIM','GUT','CWV','CW','GT','COS','WT']
names={'H':'Harness (the rig)','G':'Governance and documents','P':'Release pipeline','T':'Test infrastructure','CIM':'Crafting, Progression, Career','GUT':'GUI Tweaker','CWV':'Character Weapon Variants, Weapons of Chaos','CW':'Chaos Wastes, Events, Enemies','GT':'General Tweaker, Lighting, legacy','COS':'Cosmetics, Portraits, Dialogue','WT':'Weapon Tweaker'}
wp_by_issue=collections.defaultdict(list); vp_by_issue=collections.defaultdict(list)
L=['# Index of work packages and verification packs','','Generated by `scripts/build_index.py` from the card files. Do not edit by hand.','']
tot=collections.Counter(); p0=[]
for t in order:
    path=os.path.join(P,'wp',t+'.md')
    if not os.path.exists(path): L.append(f'## Track {t}: MISSING FILE\n'); continue
    cs=cards(path,'WP')
    L+= [f'## Track {t}: {names[t]} (`wp/{t}.md`, {len(cs)} cards)','','| Card | Title | Priority | Size | Agent | Depends on | Issues |','|---|---|---|---|---|---|---|']
    for c in cs:
        f=c['fields']; pr=short(f.get('priority','?'),4).split(' ')[0]; tot[pr]+=1
        if pr=='P0': p0.append((c['id'],c['title']))
        for n in c['issues']: wp_by_issue[n].append(c['id'])
        L.append(f"| {c['id']} | {short(c['title'],70)} | {pr} | {short(f.get('size','?'),14).split(' ')[0]} | {short(f.get('agent','?'),8).split(' ')[0].rstrip(':;,')} | {short(f.get('depends on','none'),40)} | {short(' '.join('#'+str(n) for n in c['issues']) or 'none',60)} |")
    L.append('')
L+=['## Verification packs','']
vtot=0
for b in ['D1','D2','D3','D4','D5','CLOSED']:
    path=os.path.join(P,'vp',b+'.md')
    if not os.path.exists(path): L.append(f'### {b}: MISSING FILE\n'); continue
    cs=cards(path,'VP'); vtot+=len(cs)
    L+=[f'### `vp/{b}.md` ({len(cs)} packs)','','| Pack | Title | Arena | Issues |','|---|---|---|---|']
    for c in cs:
        f=c['fields']
        for n in c['issues']: vp_by_issue[n].append(c['id'])
        L.append(f"| {c['id']} | {short(c['title'],70)} | {short(f.get('arena','?'),30)} | {short(' '.join('#'+str(n) for n in c['issues']),80)} |")
    L.append('')
L[3:3]=[f"Totals: {sum(tot.values())} work packages ({', '.join(f'{k} {v}' for k,v in sorted(tot.items()))}), {vtot} verification packs.",'','## P0 cards (do these first)','']+[f'- `{i}` {t}' for i,t in p0]+['']
open(os.path.join(A,'deliver','INDEX.md'),'w',encoding='utf-8',newline='\n').write('\n'.join(L)+'\n')
# ledger join
src=os.path.join(A,'data','MASTER_LEDGER.tsv'); rows=list(csv.reader(open(src,encoding='utf-8'),delimiter='\t',quoting=csv.QUOTE_NONE))
hdr=rows[0]+['verification_pack','fix_cards']; out=[hdr]; cov=collections.Counter()
for r in rows[1:]:
    n=int(re.sub(r'\D','',r[0])); vp=' '.join(vp_by_issue.get(n,[])); wp=' '.join(wp_by_issue.get(n,[]))
    cov['vp' if vp else 'no-vp']+=1; cov['wp' if wp else 'no-wp']+=1
    out.append(r+[vp,wp])
with open(os.path.join(A,'deliver','ISSUE_LEDGER.tsv'),'w',encoding='utf-8',newline='\n') as f:
    for r in out: f.write('\t'.join(x.replace('\\t',' ').replace('\t',' ') for x in r)+'\n')
print('work packages',sum(tot.values()),dict(tot),'| verification packs',vtot,'| ledger coverage',dict(cov)); print('P0:',len(p0))
