#requires -Version 7
<#
.SYNOPSIS
  Generates tools/harness/modsets.psd1, the named mod sets a rig plan can load with "modset" (WP-H-08 step 1).

.DESCRIPTION
  Every set lists the Vermintide Mod Framework first (Workshop folder 1369573612, VMF id "VMF"), then Workshop ids in
  tools/mod-inventory.psd1 order, with the matching VMF mod ids for the plan's expect_mods.

    public-all     every row with Public = $true
    dev-all        every row with Stream 'dev' or 'single', except the '<Dir>_dev' twin of a 'single' row
                   (weapon_tweaker_dev): both twins register the same chat command and write the same game data
                   (qa/runtime/reports/sweep-2026-11-15.md, cause A)
    dev-all-<twin> dev-all with that twin in place of its single row (dev-all-wtdev)
    no-mp          dev-all without modded_progression; it keeps cosmetics_tweaker, whose embedded More Items Library
                   (cosmetics_tweaker/scripts/mods/cosmetics_tweaker/_moreitemslibrary_embedded.lua) the item mods use
    <Dir>          one set per inventory row: that mod alone, plus cosmetics_tweaker first when the mod's scripts look up
                   "MoreItemsLibrary" with get_mod("MoreItemsLibrary") or pcall(resolve_mod, "MoreItemsLibrary")
                   (MOD_DEPENDENCIES.md: no mod hard-requires another; More Items Library is the one provider the item
                   mods cannot work without)

  -Check compares the committed file with a fresh generation and exits 2 on a difference (nothing written).
  Exit codes: 0 written or up to date, 2 drift or error.
#>
[CmdletBinding()]
param(
    [string] $Inventory = (Join-Path $PSScriptRoot '..\mod-inventory.psd1'),
    [string] $RepoRoot = (Join-Path $PSScriptRoot '..\..'),
    [string] $OutFile = (Join-Path $PSScriptRoot 'modsets.psd1'),
    [switch] $Check,
    [switch] $Quiet
)
$ErrorActionPreference = 'Stop'
$vmfWorkshopId = '1369573612'
$milProvider = 'cosmetics_tweaker'
$inv = Import-PowerShellDataFile -LiteralPath $Inventory
$rows = @($inv.Mods | Where-Object { -not [string]::IsNullOrWhiteSpace([string]$_.WorkshopId) })

function Use-Mil([string] $dir) {
    if ($dir -eq $milProvider) { return $false }
    $scripts = Join-Path $RepoRoot "$dir\scripts"
    if (-not (Test-Path -LiteralPath $scripts -PathType Container)) { return $false }
    foreach ($f in Get-ChildItem -LiteralPath $scripts -Recurse -File -Filter '*.lua') {
        if ([regex]::IsMatch([System.IO.File]::ReadAllText($f.FullName), '\b(get_mod|resolve_mod)\b\s*[(,]\s*["'']MoreItemsLibrary["'']')) { return $true }
    }
    return $false
}

function New-Set([object[]] $members, [string] $what) {
    $ids = @($vmfWorkshopId) + @($members | ForEach-Object { [string]$_.WorkshopId })
    $modIds = @('VMF') + @($members | ForEach-Object { [string]$_.ModId })
    [ordered]@{ What = $what; WorkshopIds = $ids; ModIds = $modIds }
}

$devRows = @($rows | Where-Object { $_.Stream -in 'dev', 'single' })
$twins = @(foreach ($r in $devRows) {
        if ($r.Stream -ne 'single') { continue }
        $twin = @($devRows | Where-Object { $_.Stream -eq 'dev' -and $_.Dir -eq ($r.Dir + '_dev') })
        if ($twin.Count) { [pscustomobject]@{ Single = $r; Twin = $twin[0] } }
    })
$twinDirs = @($twins | ForEach-Object { $_.Twin.Dir })
$devAll = @($devRows | Where-Object { $twinDirs -notcontains $_.Dir })

$sets = [ordered]@{}
$sets['public-all'] = New-Set @($rows | Where-Object { $_.Public -eq $true }) 'rows with Public = $true'
$sets['dev-all'] = New-Set $devAll ("rows with Stream 'dev' or 'single', without " + (($twins | ForEach-Object { "$($_.Twin.Dir) (twin of $($_.Single.Dir))" }) -join ', '))
foreach ($t in $twins) {
    $members = @($devAll | ForEach-Object { if ($_.Dir -eq $t.Single.Dir) { $t.Twin } else { $_ } })
    $sets['dev-all-' + ($t.Twin.ModId -replace '_', '')] = New-Set $members "dev-all with $($t.Twin.Dir) in place of $($t.Single.Dir)"
}
$sets['no-mp'] = New-Set @($devAll | Where-Object { $_.Dir -ne 'modded_progression' }) 'dev-all without modded_progression; cosmetics_tweaker stays for its embedded More Items Library'
$provider = @($rows | Where-Object { $_.Dir -eq $milProvider })[0]
foreach ($r in $rows) {
    if (Use-Mil $r.Dir) { $sets[$r.Dir] = New-Set @($provider, $r) "$($r.Dir) with $milProvider (More Items Library)" }
    else { $sets[$r.Dir] = New-Set @($r) "$($r.Dir) alone" }
}

function Format-List([object[]] $items) { '@(' + (($items | ForEach-Object { "'" + ($_ -replace "'", "''") + "'" }) -join ', ') + ')' }
$sb = [System.Text.StringBuilder]::new()
[void]$sb.Append("# tools/harness/modsets.psd1: named mod sets for a rig plan's `"modset`" field (WP-H-08).`n")
[void]$sb.Append("# GENERATED by tools/harness/New-ModSets.ps1 from tools/mod-inventory.psd1; do not edit by hand. Pure data.`n")
[void]$sb.Append("@{`n    Sets = @{`n")
foreach ($k in $sets.Keys) {
    $s = $sets[$k]
    [void]$sb.Append("        '$k' = @{`n")
    [void]$sb.Append("            What        = '$($s.What -replace "'", "''")'`n")
    [void]$sb.Append("            WorkshopIds = $(Format-List $s.WorkshopIds)`n")
    [void]$sb.Append("            ModIds      = $(Format-List $s.ModIds)`n")
    [void]$sb.Append("        }`n")
}
[void]$sb.Append("    }`n}`n")
$text = $sb.ToString()

if ($Check) {
    $current = if (Test-Path -LiteralPath $OutFile -PathType Leaf) { [System.IO.File]::ReadAllText($OutFile) -replace "`r`n", "`n" } else { $null }
    if ($current -cne $text) { Write-Host "[modsets] DRIFT -- $OutFile differs from a fresh generation; run tools/harness/New-ModSets.ps1" -ForegroundColor Red; exit 2 }
    if (-not $Quiet) { Write-Host "[modsets] OK -- $($sets.Count) sets up to date" }
    exit 0
}
[System.IO.File]::WriteAllText($OutFile, $text, [System.Text.UTF8Encoding]::new($false))
if (-not $Quiet) { Write-Host "[modsets] wrote $($sets.Count) sets to $OutFile" }
exit 0
